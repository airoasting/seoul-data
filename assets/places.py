def norm(text: str) -> str:
    """비교용으로 줄인다. 공백, 가운뎃점, 괄호 기호를 빼고 소문자로."""
    return re.sub(r"[\s·\.\-()（）]", "", (text or "")).lower()


_NORM = {norm(n): n for n in ALL}
_ALIAS = {norm(k): v for k, v in ALIASES.items()}
_TAIL = re.compile(r"(역|동|거리|공원|시장|특구)$")     # '구'는 떼지 않는다. 양천구가 안양천으로 읽히면 안 된다


def resolve(query: str) -> tuple[str | None, list[str]]:
    """(확정된 공식 장소명, 후보 목록). 하나로 좁혀지면 확정하고, 여럿이면 후보만 준다.

    순서: 정확 일치 → 별칭 → 부분 일치(하나뿐이고 이름의 앞에서부터 60% 이상을 덮으면 확정, 아니면 후보)
          → '동·역' 같은 꼬리를 뗀 부분 일치(후보로만) → 글자가 비슷한 이름(오타, 후보로만).
    짧은 글자가 겹친다고 확정하지 않는 이유는, 엉뚱한 장소의 수치를 답으로 내보내는 것보다 한 번 되묻는 편이
    낫기 때문이다. '양천'이 안양천인지, '망원'이 망원한강공원인지는 서버가 정할 일이 아니다.
    """
    q = norm(query)
    if not q:
        return None, []
    if q in _NORM:
        return _NORM[q], []
    if q in _ALIAS:
        return _ALIAS[q], []
    hits = [name for key, name in _NORM.items() if q in key]
    if len(hits) == 1 and norm(hits[0]).startswith(q) and len(q) >= 0.6 * len(norm(hits[0])):
        return hits[0], []
    if not hits:
        core = _TAIL.sub("", q)
        if len(core) >= 2 and core != q:
            hits = ([_ALIAS[core]] if core in _ALIAS else []) + [n for k, n in _NORM.items() if core in k]
            hits = list(dict.fromkeys(hits))
    if not hits and not q.endswith("구"):                 # 오타일 수 있다. 글자가 비슷한 이름을 후보로 준다 (자치구 이름은 빼고)
        pool = {**_ALIAS, **_NORM}                        # 별칭의 오타도 잡는다 ('성수둥' → 성수동 → 성수카페거리)
        hits = list(dict.fromkeys(pool[k] for k in difflib.get_close_matches(q, list(pool), n=3, cutoff=0.6)))
    return None, hits[:8]
